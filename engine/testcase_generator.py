def _parse_testing_types(custom_prompt: str) -> tuple[list[str], bool]:
    """Detect testing-type narrowing in the custom prompt.

    Returns ``(types, is_narrowed)``:
      * ``types``       - canonical type labels mentioned in the prompt
      * ``is_narrowed`` - True only when the prompt explicitly narrows
        scope (e.g. "smoke only", "только перформанс"). When the prompt
        merely *mentions* types alongside other content, we keep the
        full default scope so the user gets comprehensive regression
        coverage by default.
    """
    if not custom_prompt:
        return ([], False)
    lower = custom_prompt.lower()

    found: list[str] = []
    for canonical, kws in _TESTING_TYPE_KEYWORDS.items():
        if any(kw in lower for kw in kws):
            found.append(canonical)

    # Narrowing markers — same word in any of the supported languages.
    # Operator video prompted "smoke (тільки основний функціонал)" and
    # "e2e (критичний функціонал)" — the parenthetical hints carry the
    # narrowing intent, so we also recognise "критичн", "core",
    # "essential", "main", "основн" as narrowing flags.
    NARROW_TOKENS = ("only", "лише", "тільки", "только", "focus on",
                     "фокус на", "перевір лише", "проверь только",
                     "just ", "exclusively",
                     "critical", "критичн", "критический",
                     "core ", "essential", "main functionality",
                     "основн функціонал", "основной функционал",
                     "основн functionality", "(core)", "(critical)",
                     "(critical functionality)")
    # Anti-narrowing markers — when present they explicitly request the
    # FULL set even though a testing-type keyword is in the prompt
    # (e.g. "regression — full coverage" mentions Regression but should
    # NOT collapse the output).
    BROADEN_TOKENS = ("full coverage", "повне покриття", "полное покрытие",
                      "comprehensive", "all-encompassing")
    if any(tok in lower for tok in BROADEN_TOKENS):
        return (found, False)
    is_narrowed = bool(found) and any(tok in lower for tok in NARROW_TOKENS)
    return (found, is_narrowed)


def _detect_testing_type(*, summary: str, section: str, category: str) -> str:
    """Tag an existing TC/Check item with its dominant testing type.

    Heuristic, runs over the generated case after the area-specific
    generators have already populated section/category. Used so we can
    filter the output by user-requested testing type without touching
    every generator.
    """
    s = (summary or "").lower()
    sec = (section or "").lower()

    # Section name beats summary heuristics — most generators name the
    # section after the testing type they target.
    if "performance" in sec or "browser: performance" in sec:
        return "Performance"
    if "security" in sec:
        return "Security"
    if "accessibility" in sec:
        return "Accessibility"
    if "responsive" in sec:
        return "Compatibility"
    if "seo" in sec:
        return "SEO"
    if "usability" in sec or "ui / ux" in sec:
        return "Usability"
    if "localization" in sec:
        return "Localization"

    # Summary heuristics for cases not anchored by section name.
    if any(k in s for k in ("https", "csrf", "xss", "sql injection",
                              "secure", "encryption", "permissions")):
        return "Security"
    if any(k in s for k in ("3 seconds", "load time", "loaded slowly",
                              "loaded successfully", "ms", "performance")):
        return "Performance"
    if any(k in s for k in ("alt text", "keyboard navigation", "screen reader",
                              "wcag", "focus indicator", "accessib")):
        return "Accessibility"
    if any(k in s for k in ("responsive", "viewport", "375px", "768px",
                              "1280px", "tablet", "mobile viewport")):
        return "Compatibility"
    if any(k in s for k in ("meta description", "open graph", "og:",
                              "robots.txt", "sitemap.xml", "canonical")):
        return "SEO"
    if any(k in s for k in ("readable", "hover state", "focus state",
                              "above the fold", "primary call-to-action",
                              "user-friendly")):
        return "Usability"
    if any(k in s for k in ("translation", "language switch", "lang attribute",
                              "multilingual", "locale")):
        return "Localization"

    if (category or "").lower() == "security":
        return "Security"
    return "Functional"


def _parse_tc_prompt(custom_prompt: str) -> dict:
    """Parse custom prompt into directives for test case generation."""
    directives: dict = {
        "categories": None,       # e.g. ["Positive", "Negative"]
        "extra_scenarios": [],     # forced scenario types
        "testing_types": None,    # narrowing list, None = keep all (regression)
    }
    if not custom_prompt:
        return directives

    lower = custom_prompt.lower()

    # Filter by categories
    requested_cats = []
    if "positive" in lower and "only" in lower:
        requested_cats = ["Positive"]
    elif "negative" in lower and "only" in lower:
        requested_cats = ["Negative"]
    elif "security" in lower and ("only" in lower or "focus" in lower):
        requested_cats = ["Security"]
    else:
        if "positive" in lower:
            requested_cats.append("Positive")
        if "negative" in lower:
            requested_cats.append("Negative")
        if "edge" in lower or "boundary" in lower:
            requested_cats.append("Edge Case")
        if "security" in lower:
            requested_cats.append("Security")
    if requested_cats:
        directives["categories"] = requested_cats

    # Force extra scenarios
    scenario_keywords = {
        "auth": ["auth", "login", "register"],
        "security": ["security", "injection", "xss"],
        "payment": ["payment", "checkout"],
        "search": ["search", "filter"],
        "performance": ["performance", "load"],
    }
    for scenario, kws in scenario_keywords.items():
        if any(kw in lower for kw in kws):
            directives["extra_scenarios"].append(scenario)

    # Testing-type narrowing — only kick in when the user explicitly
    # restricts scope (e.g. "smoke only"). Mere mentions are ignored
    # so the default behaviour stays comprehensive regression scope.
    types, is_narrowed = _parse_testing_types(custom_prompt)
    if is_narrowed and types:
        directives["testing_types"] = types

    # Free-form focus markers — "focus on forms", "тільки на формах",
    # "сфокусуйся на login flow", "тест-кейси для форм", "tests for
    # the login flow". When matched, we extract the focus phrase as
    # a list of keyword tokens; the generator drops every TC whose
    # summary/section/steps contain none of them.
    import re as _re
    _FOCUS_RE = _re.compile(
        r"(?:focus(?:\s+(?:on|только|лише|тільки))?|"
        r"тільки\s+на|лише\s+на|сфокусуйся\s+на|сосредоточь(?:ся)?\s+на|"
        r"only\s+on|just\s+on|"
        # Operator natural-language patterns (added 2026-05-02): the
        # prompt video literally said "написати тест-кейси для форм"
        # and "tests for the login flow". Recognise both.
        r"(?:test\s*cases?|tests|тест[-\s]?кейс[ии]?|чек[-\s]?лист[ии]?)\s+(?:for|для|про)|"
        r"написати\s+(?:тест[-\s]?кейс[ии]?|чек[-\s]?лист[ии]?)\s+(?:для|про)|"
        r"generate\s+(?:test\s*cases?|tests|checklist[s]?)\s+for"
        r")\s+(.+?)(?:[\.\!\?\n]|$)",
        _re.IGNORECASE,
    )

    # Per-field fan-out trigger: "all fields", "every field", "усі
    # поля", "кожне поле", "with all fields", "з усіма полями" — when
    # present alongside a forms-focus, the generator emits one TC per
    # detected form field instead of a single "submit form" case.
    _ALL_FIELDS_RE = _re.compile(
        r"(?:all\s+fields|every\s+field|each\s+field|"
        r"all\s+inputs|each\s+input|"
        r"усі\s+поля|кожне\s+поле|кожне\s+з\s+полів|"
        r"all\s+form\s+fields|all\s+the\s+fields|"
        r"з\s+усіма\s+полями|з\s+кожним\s+полем|"
        r"per[-\s]?field|по\s+кожному\s+полю|"
        r"with\s+all\s+fields)",
        _re.IGNORECASE,
    )
    if _ALL_FIELDS_RE.search(custom_prompt):
        directives["expand_fields"] = True
    # Strip the matched phrase so the focus tokenizer sees a clean
    # noun phrase ("login flow" instead of "login flow with all
    # fields").
    custom_prompt_clean = _ALL_FIELDS_RE.sub(" ", custom_prompt)
    focus_tokens: list[str] = []
    # Drop any URL fragment from the focus phrase before tokenisation;
    # otherwise a host like "testfort.com" leaks "testfort" into the
    # keyword list and over-narrows the kept TCs.
    _URL_STRIP_RE = _re.compile(r"https?://\S+|\b\w+\.[a-z]{2,}\b",
                                _re.IGNORECASE)
    for m in _FOCUS_RE.finditer(custom_prompt_clean):
        phrase = (m.group(1) or "").strip()
        phrase = _URL_STRIP_RE.sub(" ", phrase)
        # Split on common joiners so "forms, login" → ["form","login"].
        for tok in _re.split(r"[,/\s]+", phrase):
            tok = tok.strip().lower()
            if not tok or tok in {
                # English fillers
                "the", "a", "an", "and", "or", "i", "to", "in", "on",
                "for", "of", "with", "all", "any", "every", "each",
                "fields", "field", "input", "inputs",
                # Ukrainian / Russian fillers
                "усіма", "усі", "усе", "кожне", "кожен", "кожним",
                "полями", "поля", "поле", "полів",
                "та", "і", "й", "у", "в", "на", "до", "по", "з",
                "и", "или", "все", "каждый", "каждое", "поле",
            }:
                continue
            if len(tok) < 3:
                continue
            # Drop bare URLs — the URL itself is fed elsewhere as a
            # requirement; carrying it through as a keyword filter
            # would discard every TC that doesn't literally name the
            # domain.
            if tok.startswith("http") or "." in tok:
                continue
            focus_tokens.append(tok)
    if focus_tokens:
        directives["focus_tokens"] = list(dict.fromkeys(focus_tokens))[:6]

    return directives


