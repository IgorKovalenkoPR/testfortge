def _generate_per_field_cases(analysis, *, next_section: int,
                              section_map: dict, section_counters: dict
                              ) -> list:
    """Fan-out form coverage by emitting one TC per detected input.

    For every (page, form, field) tuple that the crawler captured we
    produce three cases: required-validation, valid-input,
    boundary-overflow. The result is appended to the existing pack;
    section "Forms — Fields" gets its own section number so the
    output is grouped predictably in the UI.
    """
    out: list = []
    pages = getattr(analysis, "site_pages", None) or []
    if not pages:
        return out

    section = "Forms — Fields"
    if section not in section_map:
        section_map[section] = next_section
        section_counters[next_section] = 1
        next_section += 1

    sn = section_map[section]

    def _new_id() -> str:
        idx = section_counters[sn]
        tc_id = f"SC{sn}_{idx:03d}"
        section_counters[sn] = idx + 1
        return tc_id

    for page in pages:
        forms = page.get("forms") or []
        page_url = page.get("url") or ""
        for f_ix, form in enumerate(forms, start=1):
            fields = form.get("fields") or form.get("inputs") or []
            for field in fields:
                if isinstance(field, dict):
                    name = (field.get("name") or field.get("placeholder")
                            or field.get("label") or field.get("id")
                            or f"field-{f_ix}")
                    ftype = (field.get("type") or "text").lower()
                else:
                    name = str(field) or f"field-{f_ix}"
                    ftype = "text"
                base = {
                    "preconditions": (
                        f"User on {page_url}; form #{f_ix} is visible"
                        if page_url else f"Form #{f_ix} is visible"
                    ),
                    "test_data": f"Field: '{name}' (type={ftype})",
                    "category": "Negative",
                    "priority": "High",
                }
                # 1) required-validation: leave field empty, fill rest.
                out.append(TestCase(
                    id=_new_id(), section=section, section_num=sn,
                    summary=f"Verify '{name}' field rejects empty input "
                            f"and shows validation error",
                    preconditions=base["preconditions"],
                    test_steps=(
                        f"1. Open the page with form\n"
                        f"2. Fill every field except '{name}'\n"
                        f"3. Submit the form\n"
                        f"4. Inspect the response and the field"),
                    test_data=base["test_data"],
                    expected_result=(
                        f"The form does not submit. An inline validation "
                        f"error is displayed next to '{name}' or summarised "
                        f"at the top. Focus is moved to the offending "
                        f"field."),
                    category="Negative", priority="High",
                ))
                # 2) valid input — type-aware.
                if ftype in ("email",):
                    valid = "tester@example.com"
                    bad = "tester@"
                elif ftype in ("tel", "phone"):
                    valid = "+380501234567"
                    bad = "+38050"
                elif ftype in ("url", "website"):
                    valid = "https://example.com"
                    bad = "ht!ps://"
                elif ftype in ("number"):
                    valid = "42"
                    bad = "abc"
                elif ftype in ("password",):
                    valid = "Str0ngP@ss!2026"
                    bad = "1"
                else:
                    valid = "Sample input value 123"
                    bad = ""
                out.append(TestCase(
                    id=_new_id(), section=section, section_num=sn,
                    summary=f"Verify '{name}' field accepts a valid value "
                            f"and clears errors",
                    preconditions=base["preconditions"],
                    test_steps=(
                        f"1. Open the page with form\n"
                        f"2. Type a valid value into '{name}': {valid}\n"
                        f"3. Tab away from the field"),
                    test_data=f"{base['test_data']}; valid={valid!r}",
                    expected_result=(
                        f"Any prior validation error on '{name}' clears. "
                        f"The submit button becomes enabled when all "
                        f"required fields are filled."),
                    category="Positive", priority="High",
                ))
                # 3) Boundary overflow — type-aware.
                if ftype in ("email",):
                    overflow = "a" * 250 + "@x.com"
                elif ftype == "number":
                    overflow = "9" * 12
                else:
                    overflow = "X" * 1024
                out.append(TestCase(
                    id=_new_id(), section=section, section_num=sn,
                    summary=f"Verify '{name}' enforces a sensible max "
                            f"length / value",
                    preconditions=base["preconditions"],
                    test_steps=(
                        f"1. Open the page with form\n"
                        f"2. Paste an oversized value into '{name}': "
                        f"{len(overflow)} chars\n"
                        f"3. Submit the form"),
                    test_data=f"{base['test_data']}; overflow_len="
                             f"{len(overflow)}",
                    expected_result=(
                        f"The field either rejects the input client-side "
                        f"(maxlength enforced, error shown) or the server "
                        f"rejects with a 4xx and a clear message. No "
                        f"silent truncation, no 500."),
                    category="Negative", priority="High",
                ))
    return out


def generate_test_cases(stories: list[UserStory], custom_prompt: str = "",
                        raw_requirements: list[dict] | None = None) -> list[TestCase]:
    """Generate professional test cases using QA persona.

    The Senior QA Engineer persona analyzes input to determine testing areas
    and generates domain-specific test cases from the ISTQB knowledge base,
    then supplements with story-specific cases for any requirements not
    covered by the knowledge base.
    """
    from .qa_persona import (analyze_input, generate_professional_test_cases,
                             is_instruction)

    # Build requirements list for the persona
    reqs = raw_requirements or []
    if not reqs and stories:
        reqs = [{"text": s.original_text} for s in stories]

    # Filter out instruction lines
    reqs = [r for r in reqs if not is_instruction(r.get("text", ""))]

    analysis = analyze_input(reqs, custom_prompt)
    pro_templates = generate_professional_test_cases(analysis, stories, custom_prompt)

    # Convert TCTemplate → TestCase with TestFort IDs
    all_cases: list[TestCase] = []
    section_map: dict[str, int] = {}  # section_name → section_num
    section_counters: dict[int, int] = {}  # section_num → next idx
    next_section = 1

    directives = _parse_tc_prompt(custom_prompt)

    for tmpl in pro_templates:
        section = tmpl.section or "General"
        if section not in section_map:
            section_map[section] = next_section
            section_counters[next_section] = 1
            next_section += 1

        sn = section_map[section]
        idx = section_counters[sn]
        tc_id = f"SC{sn}_{idx:03d}"
        section_counters[sn] = idx + 1

        steps_text = "\n".join(f"{i+1}. {s}" for i, s in enumerate(tmpl.steps))
        # Tag each TC with its dominant testing type. We honour the
        # template's own ``testing_type`` when set (e.g. SEO / Usability /
        # Localization generators set it explicitly); otherwise we fall
        # back to a section/summary heuristic so older generators still
        # get correct labels without code changes per generator.
        tt = getattr(tmpl, "testing_type", "") or _detect_testing_type(
            summary=tmpl.summary, section=tmpl.section, category=tmpl.category,
        )
        tc = TestCase(
            id=tc_id, section=section, section_num=sn,
            summary=tmpl.summary, preconditions=tmpl.preconditions,
            test_steps=steps_text, test_data=tmpl.test_data,
            expected_result=tmpl.expected_result,
            category=tmpl.category, priority=tmpl.priority,
        )
        # Stash testing_type on the TC so exporters / UI / filters can
        # pick it up. Older code paths that read TestCase as a dataclass
        # won't break — getattr with default keeps back-compat.
        try:
            tc.testing_type = tt
        except Exception:
            pass
        all_cases.append(tc)

    # Apply custom prompt category filter
    if directives["categories"]:
        all_cases = [tc for tc in all_cases if tc.category in directives["categories"]]

    # Apply custom-prompt testing-type narrowing. When the prompt asks
    # for "smoke only" / "performance focus" / "тільки security", we
    # keep just the matching scope. Otherwise (default) the full
    # regression-scope set passes through unchanged.
    if directives.get("testing_types"):
        wanted = set(directives["testing_types"])
        all_cases = [tc for tc in all_cases if getattr(tc, "testing_type", "Functional") in wanted]

    # Free-form focus filter — "focus on forms / login flow / тільки
    # на формах" keeps only TCs whose summary, section, steps, or
    # expected_result mention any focus token. Saves a round-trip
    # back to the generator for the operator who wants targeted runs
    # without re-typing requirements.
    if directives.get("focus_tokens"):
        toks = [t for t in directives["focus_tokens"] if t]
        if toks:
            def _hit(tc):
                blob = " ".join((
                    tc.summary or "", tc.section or "",
                    tc.test_steps or "", tc.expected_result or "",
                    tc.preconditions or "", tc.test_data or "",
                )).lower()
                return any(tok in blob for tok in toks)
            kept = [tc for tc in all_cases if _hit(tc)]
            # Don't empty the list out completely — if nothing matched,
            # fall back to the full set so the operator still sees
            # something. We log this implicitly by flag-only behaviour.
            if kept:
                all_cases = kept

    # Per-field fan-out (Feature: "test cases for forms with all
    # fields"). When the prompt asked for it AND the persona's site
    # crawler captured form structures, emit one TC per detected
    # field — empty value, valid value, boundary value — so the
    # output covers each input rather than the single "submit form"
    # case that comes out of the canned templates.
    if directives.get("expand_fields"):
        from .qa_persona import analyze_input as _re_analyze
        try:
            extra_cases = _generate_per_field_cases(
                analysis,
                next_section=next_section,
                section_map=section_map,
                section_counters=section_counters,
            )
        except Exception as exc:
            extra_cases = []
        if extra_cases:
            all_cases.extend(extra_cases)

    # QA Team Lead review — validate and auto-fix documentation quality
    from .qa_team_lead import review_test_cases
    all_cases, _review_report = review_test_cases(all_cases)

    return all_cases


def generate_checklist(stories: list[UserStory], custom_prompt: str = "",
                       raw_requirements: list[dict] | None = None) -> list[ChecklistItem]:
    """Generate a professional low-level checklist using QA persona.

    The Senior QA Engineer persona analyzes input to determine testing areas
    and generates domain-specific checks from the ISTQB knowledge base.
    """
    from .qa_persona import analyze_input, generate_professional_checklist, is_instruction

    # Build requirements list for the persona
    reqs = raw_requirements or []
    if not reqs and stories:
        reqs = [{"text": s.original_text} for s in stories]

    # Filter out instruction lines
    reqs = [r for r in reqs if not is_instruction(r.get("text", ""))]

    analysis = analyze_input(reqs, custom_prompt)
    pro_items = generate_professional_checklist(analysis, custom_prompt)

    # Convert to ChecklistItem with TestFort IDs
    items: list[ChecklistItem] = []
    prefix_counters: dict[str, int] = {}
    from .qa_knowledge_loader import LOADER

    directives = _parse_tc_prompt(custom_prompt)
    for item in pro_items:
        prefix = LOADER.get_section_prefix(item.section) or "GEN"
        if prefix not in prefix_counters:
            prefix_counters[prefix] = 1
        counter = prefix_counters[prefix]

        tt = getattr(item, "testing_type", "") or _detect_testing_type(
            summary=item.objective, section=item.section, category=item.category,
        )
        cl_item = ChecklistItem(
            id=f"{prefix}_{counter:03d}",
            section=item.section,
            objective=item.objective,
            category=item.category,
            priority=item.priority,
        )
        try:
            cl_item.testing_type = tt
        except Exception:
            pass
        items.append(cl_item)
        prefix_counters[prefix] = counter + 1

    # Apply custom-prompt testing-type narrowing — same semantics as
    # in generate_test_cases. Default scope is full regression coverage.
    if directives.get("testing_types"):
        wanted = set(directives["testing_types"])
        items = [it for it in items if getattr(it, "testing_type", "Functional") in wanted]

    # QA Team Lead review — validate and auto-fix documentation quality
    from .qa_team_lead import review_checklist
    items, _review_report = review_checklist(items)

    return items


def generate_traceability(stories: list[UserStory], test_cases: list[TestCase]) -> list[dict]:
    """Build traceability: Requirement -> User Story -> Test Cases."""
    matrix = []
    for story in stories:
        linked = [tc for tc in test_cases if tc.user_story_id == story.id]
        matrix.append({
            "requirement_id": story.requirement_id,
            "user_story_id": story.id,
            "user_story": f"As a {story.role}, I want {_short(story.action, 80)}",
            "priority": story.priority,
            "test_case_ids": [tc.id for tc in linked],
            "test_count": len(linked),
            "categories": sorted(set(tc.category for tc in linked)),
        })
    return matrix
