    if lang == "ua":
        return ChatReply(
            text="Будь ласка! Якщо виникнуть питання — просто напишіть.",
            intent="gratitude",
        )
    return ChatReply(
        text="You're welcome! Ping me any time.",
        intent="gratitude",
    )


