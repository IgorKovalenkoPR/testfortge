def _module_help(key: str, lang: str) -> ChatReply:
    cards = _HELP_UA if lang == "ua" else _HELP_EN
    text = cards.get(key, "")
    if not text:
        return _default_help(lang)
    suggestions = _related_suggestions(key, lang)
    return ChatReply(text=text, intent=f"help_{key}", suggestions=suggestions)


