"""
TestFortge — Interactive QA Assistant (chatbot)

A small rule-based assistant that lives in the bottom-right corner of
every page. It plays two roles:

1. **Help-desk for end users** — answers "what is X?", "how do I X?",
   "where is X?" style questions about every TestFortge module
   (Estimation, Test Cases, Checklist, Test Execution, Automation QA,
   Bug Reports, credentials, site crawling, etc.).

2. **Requirement-clarifier for the generated QA Engineers** — when the
   user types a raw requirement or a vague request, the bot asks
   targeted clarification questions (domain, scope, roles, data,
   edge-cases) so the downstream generators have enough context to
   produce high-quality output.

The module is intentionally dependency-free and deterministic so the
tests can assert on the exact replies. Every reply has an EN and UA
counterpart; the caller passes ``lang`` explicitly.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Callable


# ═══════════════════════════════════════════════════════════════════
# Reply envelope
# ═══════════════════════════════════════════════════════════════════

@dataclass
class ChatReply:
    """One reply from the assistant."""
    text: str
    intent: str = "generic"
    suggestions: list[str] = field(default_factory=list)
    # When the bot is asking clarification questions it sets
    # ``follow_up`` so the UI can show them as quick-reply chips.
    follow_up: list[str] = field(default_factory=list)


# ═══════════════════════════════════════════════════════════════════
# Small helpers
# ═══════════════════════════════════════════════════════════════════

_WORD = re.compile(r"\w+", re.UNICODE)

def _norm(text: str) -> str:
    return (text or "").strip().lower()


def _any(hay: str, needles: list[str]) -> bool:
    return any(n in hay for n in needles)


